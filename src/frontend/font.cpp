int MeasureText(const std::string& text, int scale) {
    const int advance = (kGlyphWidth + 1) * scale;
    return static_cast<int>(text.size()) * advance - scale; // no trailing gap after the last glyph
}

int DrawText(SDL_Renderer* renderer, int x, int y, const std::string& text,
             int scale, SDL_Color color) {
    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);

    const auto& table = GlyphTable();
    const int advance = (kGlyphWidth + 1) * scale;
    int cursorX = x;

    for (char rawCh : text) {
        const char ch = static_cast<char>(std::toupper(static_cast<unsigned char>(rawCh)));
        const auto it = table.find(ch);
        if (it != table.end()) {
            const Glyph& glyph = *it->second;
            for (int row = 0; row < kGlyphHeight; ++row) {
                for (int col = 0; col < kGlyphWidth; ++col) {
                    if (glyph.rows[row][col] != 'X') continue;
                    SDL_Rect block{cursorX + col * scale, y + row * scale, scale, scale};
                    SDL_RenderFillRect(renderer, &block);
                }
            }
        }
        // Unrecognized characters (lowercase already handled by toupper,
        // this covers anything truly outside the font) just advance the
        // cursor with nothing drawn - a blank cell, not a hard failure.
        cursorX += advance;
    }

    return cursorX - x - scale;
}

