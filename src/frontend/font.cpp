const std::unordered_map<char, const Glyph*>& GlyphTable() {
    static const std::unordered_map<char, const Glyph*> table = [] {
        std::unordered_map<char, const Glyph*> t;
        for (const Glyph& g : kGlyphs) {
            t[g.ch] = &g;
        }
        return t;
    }();
    return table;
}

